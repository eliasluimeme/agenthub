// Compiles the demo repositories in seed/projects (and pull request patches in seed/patches)
// into src/lib/seed-projects.ts, so the seed works on hosts without the seed/ folder.
// Run after editing anything under seed/:  npm run seed:gen
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const walk = (dir) =>
  readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? (name === 'node_modules' || name === 'dist' ? [] : walk(p)) : [p];
  });
const dirs = (dir) => readdirSync(dir).filter((n) => statSync(join(dir, n)).isDirectory()).sort();

/** A plausible commit message for a file, so the file browser shows something useful. */
function message(path, content) {
  const base = path.split('/').pop().replace(/\.(test\.)?ts$/, '');
  if (path === 'README.md') return 'Document usage';
  if (path === 'package.json') return `Release v${JSON.parse(content).version}`;
  if (path.endsWith('.md')) return `Write ${base.replace(/\.md$/, '').toLowerCase()} notes`;
  if (path.endsWith('.json')) return `Add ${base}`;
  if (path.startsWith('tests/')) return `Cover ${base} with tests`;
  if (base === 'index') return 'Export public API';
  if (base === 'cli') return 'Add command line entry point';
  return `Add ${base}`;
}

const projects = {};
for (const owner of dirs(join(root, 'seed/projects'))) {
  for (const repo of dirs(join(root, 'seed/projects', owner))) {
    const dir = join(root, 'seed/projects', owner, repo);
    // README first, then the rest alphabetically: it is what people read first.
    const files = walk(dir).map((f) => relative(dir, f)).sort((a, b) => (a === 'README.md' ? -1 : b === 'README.md' ? 1 : a.localeCompare(b)));
    projects[`${owner}/${repo}`] = files.map((p) => {
      const content = readFileSync(join(dir, p), 'utf8');
      return [p, content, message(p, content)];
    });
  }
}

const patches = {};
for (const owner of dirs(join(root, 'seed/patches'))) {
  for (const repo of dirs(join(root, 'seed/patches', owner))) {
    for (const number of dirs(join(root, 'seed/patches', owner, repo))) {
      const dir = join(root, 'seed/patches', owner, repo, number);
      patches[`${owner}/${repo}#${number}`] = walk(dir).map((f) => ({ path: relative(dir, f), after: readFileSync(f, 'utf8') }));
    }
  }
}

const out = `// Generated by scripts/gen-seed-projects.mjs from seed/. Do not edit by hand.

/** owner/repo -> [path, content, commit message] */
export const PROJECTS: Record<string, [string, string, string][]> = ${JSON.stringify(projects, null, 1)};

/** owner/repo#number -> files a pull request changes, with their new content */
export const PATCHES: Record<string, { path: string; after: string }[]> = ${JSON.stringify(patches, null, 1)};
`;
writeFileSync(join(root, 'src/lib/seed-projects.ts'), out);
const count = Object.values(projects).reduce((n, f) => n + f.length, 0);
console.log(`Wrote ${Object.keys(projects).length} projects (${count} files) and ${Object.keys(patches).length} patches to src/lib/seed-projects.ts`);
